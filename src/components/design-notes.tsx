'use client';

import { useId, useRef, useState, type KeyboardEvent } from 'react';
import { ChevronDown, ExternalLink, Lightbulb } from 'lucide-react';
import {
  DEFAULT_CONFIG,
  eligibleProviders,
  simulateRequest,
  type RequestRecord,
  type RoutingConfig,
} from '@/lib/gateway';
import { createHandoffPrompt, gatewayOptions, type HandoffContext } from '@/lib/handoff';
import { getReplayEvents, type ReplayEvent } from '@/lib/replay';
import './design-notes.css';

export type DesignNoteTopic = 'routing' | 'recovery' | 'activation' | 'setup';

interface DesignNote {
  title: string;
  constraint: string;
  decision: string;
  question: string;
  sources: { label: string; href: string }[];
}

const DOCS = 'https://vercel.com/docs/ai-gateway';

const NOTES: Record<DesignNoteTopic, DesignNote> = {
  routing: {
    title: 'Preference and restriction answer different questions.',
    constraint: 'Gateway’s order prefers providers. Its only allowlist restricts providers across every model in the fallback chain. A preferred provider cannot bypass that restriction.',
    decision: 'Let developers reorder provider preferences in the route itself, with restrictions in in-page route settings. Show the remaining eligible pool and blocked fallback before a request is sent.',
    question: 'Can a developer predict which providers remain eligible after changing the allowlist, including the fallback model?',
    sources: [
      { label: 'Provider selection', href: `${DOCS}/models-and-providers/provider-filtering-and-ordering` },
      { label: 'Model fallbacks', href: `${DOCS}/models-and-providers/model-fallbacks` },
    ],
  },
  recovery: {
    title: 'A recovered request still has a failure worth seeing.',
    constraint: 'Gateway routing metadata and Logs expose provider attempts. A final successful provider alone does not explain the time spent on a failed attempt before output.',
    decision: 'Map observed attempt durations onto elapsed-time lanes. Monitoring opens the same receipt, and baseline and draft use one scale. Selecting an attempt reveals its cause; replay inspects the original evidence while testing a route creates new request identities.',
    question: 'Can someone identify where the delay occurred, then distinguish replaying evidence from sending a request with a changed route?',
    sources: [
      { label: 'Routing metadata', href: `${DOCS}/models-and-providers/provider-filtering-and-ordering` },
      { label: 'Request Logs', href: `${DOCS}/observability-and-spend/logs` },
    ],
  },
  activation: {
    title: 'Saved does not mean every new request uses it yet.',
    constraint: 'Virtual Model updates can take a few minutes to propagate. The documented slug stays stable while its configuration changes.',
    decision: 'Give saved and active configuration distinct states. Keep a request’s effective snapshot so inspecting an earlier request does not silently show today’s draft.',
    question: 'Can someone tell what is saved, what is active in the demo, and which configuration an earlier request actually used?',
    sources: [
      { label: 'Virtual Models', href: `${DOCS}/models-and-providers/virtual-models` },
    ],
  },
  setup: {
    title: 'Carry the route into the tools where setup happens.',
    constraint: 'Editor links can prepare an unsent agent draft, but cannot prove installation or server execution. A live request needs the developer’s server-side Gateway authentication; Logs can take up to 90 seconds to appear.',
    decision: 'Carry the chosen client, environment, model, authentication, and route into an editable brief. Offer a runnable server starter alongside the account-free simulation. Report each handoff as preparation, then leave live verification in the developer’s own application.',
    question: 'Can someone review the proposed integration in their own tools and distinguish a prepared draft, a demo receipt, and an actual server response?',
    sources: [
      { label: 'Getting started', href: `${DOCS}/getting-started` },
      { label: 'Authentication', href: `${DOCS}/authentication-and-byok` },
      { label: 'Request Logs', href: `${DOCS}/observability-and-spend/logs` },
      { label: 'Cursor drafts', href: 'https://cursor.com/docs/reference/deeplinks' },
      { label: 'VS Code drafts', href: 'https://code.visualstudio.com/docs/configure/command-line#_prepare-a-new-agent-session-draft' },
    ],
  },
};

const EXAMPLE_PROMPT = 'Suggest a useful support response for a customer whose invitation link has expired.';

/** Reference data is generated by the same local domain code as the demo. */
function referenceRequest(): RequestRecord {
  return simulateRequest(
    structuredClone(DEFAULT_CONFIG),
    'provider-failure',
    EXAMPLE_PROMPT,
    'demo_design_note',
  );
}

function JsonExample({ label, value }: { label: string; value: unknown }) {
  return <div className="design-notes-example">
    <span className="design-notes-code-label">{label}</span>
    <pre tabIndex={0} aria-label={label}><code>{JSON.stringify(value, null, 2)}</code></pre>
  </div>;
}

function Mechanics({ topic }: { topic: DesignNoteTopic }) {
  if (topic === 'routing') {
    const config: RoutingConfig = { ...structuredClone(DEFAULT_CONFIG), only: ['anthropic', 'bedrock'] };
    return <>
      <p>The allowlist is evaluated for each model. This example uses the curated demo catalog, not live provider availability.</p>
      <JsonExample label="Gateway request options" value={{
        model: config.model,
        providerOptions: { gateway: { order: config.order, only: config.only, models: config.fallbacks } },
      }} />
      <div className="design-notes-outcome">
        <span><strong>Primary eligible</strong><code>{eligibleProviders(config).join(', ') || 'none'}</code></span>
        <span><strong>Fallback eligible</strong><code>{eligibleProviders(config, config.fallbacks[0]).join(', ') || 'none'}</code></span>
      </div>
      <p className="design-notes-boundary"><code>fallbacks: string[]</code> is the local RoutingConfig field. Generated request code maps it to Gateway’s <code>models: string[]</code>.</p>
    </>;
  }

  if (topic === 'recovery') {
    const record = referenceRequest();
    const timeline: Pick<ReplayEvent, 'atMs' | 'kind' | 'attemptIndex'>[] = getReplayEvents(record)
      .filter(event => event.kind !== 'output')
      .map(({ atMs, kind, attemptIndex }) => ({ atMs, kind, ...(attemptIndex === undefined ? {} : { attemptIndex }) }));
    const example: Pick<RequestRecord, 'id' | 'model' | 'servedModel' | 'provider' | 'status' | 'attempts' | 'ttftMs' | 'usageKnown' | 'provenance'> = {
      id: record.id,
      model: record.model,
      servedModel: record.servedModel,
      provider: record.provider,
      status: record.status,
      attempts: record.attempts,
      ttftMs: record.ttftMs,
      usageKnown: record.usageKnown,
      provenance: record.provenance,
    };
    return <>
      <p>Reference fixture from the local simulator, not the selected request. The same <code>RequestRecord</code> retains requested model, served model, and every observed attempt.</p>
      <JsonExample label="RequestRecord · reference recovery" value={example} />
      <p className="design-notes-boundary"><code>Attempt.status</code> is <code>success | failed | excluded</code>. Excluded means no request was sent. Cancellation preserves observed attempts and partial output with <code>usageKnown: false</code>; it does not invent a final usage total.</p>
      <JsonExample label="getReplayEvents(record) · excerpt without text-reveal events" value={timeline} />
      <p className="design-notes-boundary"><code>atMs: number</code> is the position in recorded receipt milliseconds; <code>attemptIndex?: number</code> points into the same attempts array. Text reveal is interpolated from the recorded response, not historical token telemetry. Replay longer than six seconds is scaled and labeled accelerated; the displayed event times stay unchanged.</p>
      <p className="design-notes-boundary">These are local demo fields. Replay and controlled comparison are proposed experience patterns, not Gateway API endpoints or live benchmarks.</p>
    </>;
  }

  if (topic === 'activation') {
    const record = referenceRequest();
    const next: RoutingConfig = { ...structuredClone(DEFAULT_CONFIG), order: ['bedrock', 'anthropic', 'vertex'], revision: 2 };
    return <>
      <p>The demo stores separate <code>active</code> and <code>pending</code> configurations. Saving creates the pending revision; explicit simulated activation changes the configuration for subsequent demo requests.</p>
      <JsonExample label="Local configuration state · before activation" value={{
        active: { slug: DEFAULT_CONFIG.slug, revision: DEFAULT_CONFIG.revision, order: DEFAULT_CONFIG.order },
        pending: { slug: next.slug, revision: next.revision, order: next.order },
        earlierRequest: { id: record.id, revision: record.revision, configSnapshot: record.configSnapshot },
      }} />
      <p className="design-notes-boundary"><code>revision: number</code> and <code>configSnapshot?: RoutingConfig</code> belong to this prototype. This does not claim a Gateway revision-history or manual activation API, or measure real propagation time.</p>
    </>;
  }

  const context: HandoffContext = { intent: 'new', integration: 'sdk', environment: 'local', auth: 'oidc', model: DEFAULT_CONFIG.model, routingConfig: structuredClone(DEFAULT_CONFIG) };
  const prompt = createHandoffPrompt(context);
  return <>
    <p><code>createHandoffPrompt(context)</code> carries the selected setup into a reviewable editor brief. This reference example uses the default route; it is not a receipt or proof that an app is connected.</p>
    <div className="design-notes-example">
      <span className="design-notes-code-label">Prepared agent brief · reference excerpt</span>
      <pre tabIndex={0} aria-label="Prepared agent brief reference excerpt"><code>{prompt.split('\n\n').slice(0, 2).join('\n\n')}</code></pre>
    </div>
    <JsonExample label="Gateway request options carried into the brief" value={gatewayOptions(context)} />
    <div className="design-notes-outcome">
      <span><strong>Prepared editor draft</strong><span>Review before sending</span></span>
      <span><strong>Demo receipt</strong><code>provenance: 'demo'</code></span>
      <span><strong>Live connection proof</strong><span>Successful server execution</span></span>
    </div>
    <p className="design-notes-boundary">The ZIP contains a Next.js interface and a server request using the chosen client. It sends only when the developer chooses Send in their own app. Credentials stay in their server environment; this prototype accepts no real key and calls no live Gateway API. Routing a coding agent’s own traffic uses the documented CLI preview and interactive setup flow.</p>
  </>;
}

/** Optional reviewer commentary; it never changes request or routing state. */
export function DesignNotes({ topic, context = 'workspace' }: { topic: DesignNoteTopic; context?: string }) {
  const [expanded, setExpanded] = useState(false);
  const panelId = useId();
  const toggleRef = useRef<HTMLButtonElement>(null);
  const note = NOTES[topic];

  function dismissWithEscape(event: KeyboardEvent<HTMLElement>) {
    if (event.key !== 'Escape' || !expanded) return;
    event.preventDefault();
    event.stopPropagation();
    setExpanded(false);
    toggleRef.current?.focus();
  }

  return <aside className="design-notes" aria-label={`Design reasoning in ${context}: ${note.title}`} onKeyDown={dismissWithEscape}>
    <button
      ref={toggleRef}
      type="button"
      className="design-notes-toggle"
      aria-expanded={expanded}
      aria-controls={panelId}
      onClick={() => setExpanded(value => !value)}
    >
      <Lightbulb size={15} aria-hidden="true" />
      <span>Why this design?</span>
      <span className="design-notes-reviewer">Reviewer note</span>
      <ChevronDown size={14} className="design-notes-chevron" aria-hidden="true" />
    </button>
    <div id={panelId} className="design-notes-panel" hidden={!expanded}>
      <h3>{note.title}</h3>
      <dl className="design-notes-reasoning">
        <div><dt>Constraint <span>Documented platform</span></dt><dd>{note.constraint}</dd></div>
        <div><dt>Decision <span>Proposed experience</span></dt><dd>{note.decision}</dd></div>
        <div><dt>To validate <span>Open question</span></dt><dd>{note.question}</dd></div>
      </dl>
      <p className="design-notes-research">These decisions have not been validated with user research or production traffic.</p>
      <div className="design-notes-sources" aria-label="Official sources">
        {note.sources.map(source => <a key={source.href} href={source.href} target="_blank" rel="noreferrer">{source.label}<ExternalLink size={12} aria-hidden="true" /><span className="design-notes-sr-only"> (opens in a new tab)</span></a>)}
      </div>
      <details className="design-notes-mechanics">
        <summary>Inspect the mechanics<ChevronDown size={14} aria-hidden="true" /></summary>
        <div className="design-notes-mechanics-body"><Mechanics topic={topic} /></div>
      </details>
    </div>
  </aside>;
}
